    w("  - `Theme` 60 bpm, 20 bars = 80 s: low detuned pads, bass, sparse bell motif, formant choir pads")
    w("    (u/o/a vowel morphs) on four chords; ends on A major so the loop resolves into D minor.")
    w("  - `Battle` 112.5 bpm (sample-exact bars), 36 bars = 76.8 s: odaiko/taiko/mid/frame drums,")
    w("    pulsing 8th-note ostinato with 3-3-2 accents, dark low pads, breakdown with choir, brass")
    w("    swells; everything kept below ~1.3 kHz plus a -3 dB dip at 2.2 kHz to leave room for SFX")
    w("    (energy above 1 kHz is ~-30 dB re total).")
