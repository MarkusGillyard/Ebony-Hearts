    w("  rotate (3-4 passes) with a Doppler-like centre-frequency swing around each pass.")
    w("- **Wren's golden aura**: Poisson spark clusters with metallic sizzle, jittered saturated saw buzz,")
    w("  descending saw 'zap' and a warm detuned tonal shimmer (D-A-E-F#, i.e. a bright major colour).")
    w("- **Ashka's crimson flame**: turbulent two-band noise roar, crackle pops, a low 'whoomp' sweep and a")
    w("  faint dark tonal core (55-58 Hz) so the magic flame differs from ordinary fire.")
