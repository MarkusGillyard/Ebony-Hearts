    w("")
    w("Reading the table: a step well below the 99.9th percentile of ordinary sample-to-sample steps means")
    w("no click. For the music the loop point is a bar downbeat (drum hits land on sample 0), so its")
    w("spectral flux is naturally high against random points; compared with the file's other downbeats it")
    w("sits mid-distribution, i.e. the seam is indistinguishable from any other bar line.")
    w("")
    w("## Third-party material (Kenney, CC0 1.0)")
    w("")
    w("Source: Kenney 'Impact Sounds', 'Interface Sounds' and 'RPG Audio' packs (CC0, www.kenney.nl), read")
    w("only from `downloads/thirdparty/Kenney/`. Every use goes through: OGG decode (Blender audaspace) ->")
    w("mono sum -> FFT resample to 48 kHz (varispeed folded into the same step) -> the processing listed")
    w("-> peak normalise -> mixed as ONE layer with original synthesized layers, then the output's own")
    w("chain (combat: synthetic stone-room reflections; ambience: synthetic chapel reverb; all: final")
    w("mastering). No Kenney file is used unprocessed or on its own.")
    w("")
    w("| Kenney file (under `downloads/thirdparty/Kenney/`) | Used in | Processing |")
    w("|---|---|---|")
    groups = OrderedDict()
    for u in usage:
        key = (u["stem"], _proc(u))
        groups.setdefault(key, []).append(u["output"])
    pack_of = {}
    from .kenney import NEEDED, PACKS
    for p, s in NEEDED:
        pack_of[s] = PACKS[p]
    for (stem, proc), outs in sorted(groups.items()):
        outs = sorted(set(outs))
        w(f"| `{pack_of.get(stem, '?')}/{stem}.ogg` | {', '.join('`S_' + o + '`' for o in outs)} | {proc} |")
    used_stems = sorted({u["stem"] for u in usage})
    w("")
    w(f"{len(used_stems)} distinct Kenney files are used: " + ", ".join(f"`{s}`" for s in used_stems) + ".")
    w("Files that are decoded into the cache but not listed above are not used in any output.")
    w("")
    w("## Original synthesis")
    w("")
    w("Everything not listed in the Kenney table is original synthesis written for this game in")
    w("`Tools/Audio/eh_audio/` (numpy): no recorded voice, no sampled instruments, no copied or imitated")
