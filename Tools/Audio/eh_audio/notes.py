    w("- **True peak**: maximum of a 4x FFT (band-limited) interpolation of the signal; one-shots are")
    w("  normalised so this is exactly -1.0 dBTP before 16-bit TPDF-dithered quantisation.")
    w("- **RMS**: over the whole file, both channels pooled (dBFS, full-scale sine = -3 dBFS).")
    w("- **Loudness**: ITU-R BS.1770 K-weighting (the standard 48 kHz biquads, applied through their exact")
    w("  frequency response in the FFT domain), 400 ms blocks. Loops: gated integrated loudness (-70 LUFS")
    w("  absolute and -10 LU relative gates, blocks wrap across the loop point) = LUFS-I. One-shots are")
    w("  too short for integrated loudness, so the table shows the maximum momentary (400 ms) loudness,")
    w("  LUFS-M. This is an implementation of the standard's maths, not a certified meter, hence")
    w("  'LUFS-equivalent'.")
    w("- **Mono drop**: RMS of the mid channel (L+R)/2 relative to the stereo RMS. 0 dB = fully")
    w("  mono-compatible, -3 dB = uncorrelated channels. Loops have a side-level safety (side power is")
    w("  kept <= 0.5x mid power, i.e. no worse than -1.8 dB).")
    w("- **DC**: |mean| of each channel (largest shown), linear full scale.")
    w("- **Clicks**: one-shots start with 2 ms of pre-roll and a 2 ms raised-cosine fade-in, end with a")
    w("  raised-cosine fade-out (5 ms to 0.9 s depending on the tail), and the first/last samples are 0.")
    w("  Every synthesized layer also fades out at its own end, so no internal truncation clicks.")
    w("")
    w("## Seamless-loop verification")
    w("")
